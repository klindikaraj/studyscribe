LANGUAGES = tuple(_TEXTS)


def table_language(language: str | None) -> str:
    """The language whose table is used for notes written in `language`."""
    code = (language or "").lower().split("-")[0]
    return code if code in _TEXTS else FALLBACK


def text(language: str | None, key: str, **values: object) -> str:
    """The text `key` in the notes' language (English when the language has no table)."""
    template = _TEXTS[table_language(language)][key]
    return template.format(**values) if values else template
